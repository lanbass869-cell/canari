WITNESS_TS = 1761800000
ROOT_HEX = "91ef195f774f15b16cb9151fee533c7ee725a994031ad1b3aee80cf408dbac3e"


class TestHistorVectors:
    def test_checkpoint_text_parses(self):
        origin, size, root = cp.parse_checkpoint(CHECKPOINT_TEXT)
        assert (origin, size) == (ORIGIN, 8)
        assert root.hex() == ROOT_HEX

    def test_our_encoder_reproduces_their_bytes(self):
        root = bytes.fromhex(ROOT_HEX)
        assert cp.checkpoint_text(ORIGIN, 8, root) == CHECKPOINT_TEXT

    def test_vkey_parses_and_id_matches(self):
        key = cp.VerifierKey.parse(LOG_VKEY)
        assert key.name == ORIGIN
        assert key.type_byte == cp.LOG_KEY_TYPE
        assert key.key_id.hex() == "2e59bf2d"

    def test_vkey_roundtrip(self):
        key = cp.VerifierKey.parse(LOG_VKEY)
        assert cp.vkey(key.name, key.type_byte, key.public_key) == LOG_VKEY

    def test_note_parses_and_text_matches(self):
        text, sigs = cp.parse_note(CHECKPOINT_NOTE)
        assert text == CHECKPOINT_TEXT
        assert len(sigs) == 1
        assert sigs[0].name == ORIGIN

    def test_log_signature_verifies(self):
        text, sigs = cp.parse_note(CHECKPOINT_NOTE)
        assert cp.verify_log_signature(text, sigs, cp.VerifierKey.parse(LOG_VKEY))

    def test_log_signature_rejects_wrong_text(self):
        text, sigs = cp.parse_note(CHECKPOINT_NOTE)
        tampered = text.replace("8\n", "9\n", 1)
        assert not cp.verify_log_signature(tampered, sigs, cp.VerifierKey.parse(LOG_VKEY))

    def test_cosignature_verifies_with_timestamp(self):
        line = cp.parse_signature_line(COSIGNATURE_LINE.rstrip("\n"))
        ts = cp.verify_cosignature(CHECKPOINT_TEXT, line, cp.VerifierKey.parse(WITNESS_VKEY))
        assert ts == WITNESS_TS

    def test_cosignature_rejects_other_checkpoint(self):
        line = cp.parse_signature_line(COSIGNATURE_LINE.rstrip("\n"))
        other = CHECKPOINT_TEXT.replace("8\n", "9\n", 1)
        assert cp.verify_cosignature(other, line,
                                     cp.VerifierKey.parse(WITNESS_VKEY)) is None

    def test_cosignature_message_matches_their_vector(self):
        msg = cp.cosignature_message(CHECKPOINT_TEXT, WITNESS_TS)
        assert msg == (b"cosignature/v1\ntime 1761800000\n"
                       + CHECKPOINT_TEXT.encode("utf-8"))


class TestOurOwnSigning:
    def test_sign_and_verify_roundtrip(self):
        from canari.signing import generate_keypair
        signer, pub = generate_keypair()
        root = bytes(range(32))
        note = cp.sign_checkpoint(signer, "canari.example/log", 5, root)
        text, sigs = cp.parse_note(note)
        assert cp.parse_checkpoint(text) == ("canari.example/log", 5, root)
        pub_bytes = bytes.fromhex(pub.to_dict()["keyval"]["public"])
        vk = cp.VerifierKey("canari.example/log", cp.LOG_KEY_TYPE, pub_bytes)
        assert cp.verify_log_signature(text, sigs, vk)

    def test_cosign_and_verify_roundtrip(self):
        from canari.signing import generate_keypair
        signer, pub = generate_keypair()
        text = cp.checkpoint_text("canari.example/log", 3, b"\x01" * 32)
        line = cp.cosign(signer, "w.example", text, 1762000000)
        pub_bytes = bytes.fromhex(pub.to_dict()["keyval"]["public"])
        vk = cp.VerifierKey("w.example", cp.COSIGNATURE_V1_TYPE, pub_bytes)
        assert cp.verify_cosignature(text, line, vk) == 1762000000

    def test_signature_bytes_are_64_not_hex_string(self):
        """CryptoSigner returns a *hex string*; shipping it raw produced a
        128-byte field that no verifier accepts."""
        from canari.signing import generate_keypair
        signer, _pub = generate_keypair()
        line = cp.cosign(signer, "w.example", "x\n1\n" + "A" * 43 + "=\n", 1)
        assert len(line.signature) == 8 + 64


class TestStrictness:
    def test_noncanonical_base64_refused(self):
        with pytest.raises(cp.NoteError):
            cp.b64_strict("aa==")          # padding is canonical, but...
        # a truly non-canonical form: missing padding
        with pytest.raises(cp.NoteError):
            cp.b64_strict("aGVsbG8")

    def test_size_with_leading_zero_refused(self):
        with pytest.raises(cp.NoteError):
            cp.parse_checkpoint("o\n08\n" + base64.b64encode(b"\x00" * 32).decode() + "\n")

    def test_short_root_refused(self):
        with pytest.raises(cp.NoteError):
            cp.parse_checkpoint("o\n1\n" + base64.b64encode(b"\x00" * 31).decode() + "\n")

    def test_note_without_blank_line_refused(self):
        with pytest.raises(cp.NoteError):
            cp.parse_note("a\n1\n" + base64.b64encode(b"\x00" * 32).decode() + "\n")

    def test_duplicate_signature_lines_refused(self):
        line = cp.parse_signature_line(COSIGNATURE_LINE.rstrip("\n"))
        with pytest.raises(cp.NoteError):
            cp.render_note(CHECKPOINT_TEXT, [line, line])

    def test_bad_vkey_id_refused(self):
        bad = LOG_VKEY.replace("2e59bf2d", "deadbeef")
        with pytest.raises(cp.NoteError):
            cp.VerifierKey.parse(bad)

    def test_name_with_plus_refused(self):
        with pytest.raises(cp.NoteError):
            cp.check_name("a+b")

    def test_signature_line_without_em_dash_refused(self):
        with pytest.raises(cp.NoteError):
            cp.parse_signature_line("- example.com/witness AAAA")


class TestBundleAndCheckpointAgree:
    """The bundle's checkpoint and docs/log/checkpoint.txt are two renderings of
    one head. If they carry different origins, a witness co-signs one identity
    while a consumer verifies another. Found while diffing a fresh clone: the
    bundle still said the internal log_id after the published origin changed."""

    def test_bundle_checkpoint_uses_c2sp_origin(self, tmp_path):
        from canari.logstore import open_log
        L = open_log(str(tmp_path / "log"), log_id="internal-id",
                     c2sp_origin="example.org/canari/log")
        L.append({"a": 1})
        L.seal()
        b = L.export_bundle(0)
        assert b["checkpoint"].split("\n")[0] == "example.org/canari/log"
        assert L.checkpoint_note().split("\n")[0] == "example.org/canari/log"

    def test_default_origin_is_log_id(self, tmp_path):
        from canari.logstore import open_log
        L = open_log(str(tmp_path / "log2"), log_id="plain-id")
        L.append({"a": 1})
        L.seal()
        assert L.checkpoint_note().split("\n")[0] == "plain-id"

    def test_published_origin_is_namespaced(self):
        root = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
        src = open(os.path.join(root, "scripts", "publish_log.py"),
                   encoding="utf-8").read()
        assert 'C2SP_ORIGIN = "github.com/lanbass869-cell/canari/log"' in src
