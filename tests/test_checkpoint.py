"""Cross-implementation conformance for the c2sp checkpoint format.

These vectors come from `alexar76/histor`'s published test-vectors
(`test-vectors/vectors.json`, Apache-2.0). They are generated by that project's
Go reference implementation, so passing them is evidence that our bytes match
an implementation we did not write -- which is the entire point of adopting
c2sp.org/tlog-checkpoint instead of our own tree-head format.

If a future change to canari/checkpoint.py makes these fail, we are no longer
interoperable with the existing witness network and must not ship.
"""
