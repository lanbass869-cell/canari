# -*- coding: utf-8 -*-
"""Conformance against draft-templeman-scitt-measurement-capsule-01 vectors.

These vectors are published by the draft's author (CSOAI-ORG/councilof-ai,
docs/ietf/measurement-capsule-01/test-vectors, read 2026-11-15). They are
generated by gen_vectors.py on a separate code path, so passing them is evidence
that our serializer matches an implementation we did not write.

Two design rules the vectors taught us, both now enforced:

1. An UNCHECKABLE capsule records `sources.<x> = null` for what could not be
   read. My first validator rejected that as "not a digest" -- the vector was
   right and I was wrong. Null must be legal: fabricating a digest would be a
   lie, and omitting the key would erase the difference between "not read" and
   "not applicable".
2. COSE_Sign1 is CBOR tag 18. Decoding without unwrapping the tag produced
   "a COSE_Sign1 is a 4-element array" on perfectly valid input.
"""
import json
import os
import subprocess
import sys

import pytest

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
sys.path.insert(0, ROOT)

from canari import capsule as cap  # noqa: E402

VECTORS = os.path.join(ROOT, "docs", "spec", "measurement-capsule-vectors.json")

pytest.importorskip("cbor2")


@pytest.fixture(scope="module")
def V():
    with open(VECTORS, encoding="utf-8") as f:
        return json.load(f)


class TestCapsuleId:
    def test_every_published_capsule_id_reproduces(self, V):
        for c in V["V1_capsules"]:
            doc = json.loads(c["jcs_utf8"])
            assert cap.capsule_id(doc) == c["capsule_id"], doc["subject_id"]

    def test_stored_jcs_is_canonical(self, V):
        for c in V["V1_capsules"]:
            doc = json.loads(c["jcs_utf8"])
            assert cap.jcs(doc).decode("utf-8") == c["jcs_utf8"]

    def test_uncheckable_capsule_is_valid(self, V):
        """The draft's own UNCHECKABLE vector carries sources.<x> = null."""
        doc = next(json.loads(c["jcs_utf8"]) for c in V["V1_capsules"]
                   if json.loads(c["jcs_utf8"])["measurement_state"] == "UNCHECKABLE")
        assert doc["sources"]["initialize_response"] is None
        assert cap.validate_capsule(doc) == []


class TestBatch:
    def test_merkle_root(self, V):
        b = V["V2_batch"]
        assert cap.batch_root(b["leaves_sorted"]) == b["merkle_root"]

    def test_audit_path_reproduced(self, V):
        b = V["V2_batch"]
        ap = b["audit_path"]
        assert cap.audit_path(b["leaves_sorted"], ap["leaf"]) == ap["path"]

    def test_audit_path_verifies(self, V):
        b = V["V2_batch"]
        ap = b["audit_path"]
        leaf = cap._leaf(ap["leaf"])
        proof = [bytes.fromhex(p) for p in ap["path"]]
        assert cap._recompute(leaf, ap["leaf_index"], ap["tree_size"], proof) \
            == b["merkle_root"]

    def test_duplicates_rejected(self, V):
        leaves = list(V["N_controls"][-1]["leaves"])
        with pytest.raises(cap.CapsuleError) as e:
            cap.batch_root(leaves)
        assert "leaf-set-no-duplicates" in str(e.value)


class TestCose:
    """V3 and V4 are single objects, not maps of named cases. Treating them as
    maps made an earlier runner skip both groups silently while still reporting
    a full pass."""

    def test_sign1_attached_verifies(self, V):
        v = V["V3_cose_sign1_attached"]
        pub = bytes.fromhex(V["test_key"]["public_hex"])
        info = cap.verify_cose_sign1(bytes.fromhex(v["cose_sign1_hex"]), pub)
        assert info["alg"] == -19
        assert info["kid"] == b"did:web:measurer.example#test-key-1"

    def test_hash_envelope_verifies(self, V):
        v = V["V4_cose_hash_envelope"]
        pub = bytes.fromhex(V["test_key"]["public_hex"])
        info = cap.verify_cose_sign1(bytes.fromhex(v["cose_sign1_hex"]), pub,
                                     hash_envelope=True)
        assert info["payload"].hex() == v["payload_hex"]

    def test_flipped_payload_rejected(self, V):
        pub = bytes.fromhex(V["test_key"]["public_hex"])
        neg = next(n for n in V["N_controls"] if n["id"] == "N4-payload-byte-flipped")
        with pytest.raises(cap.CapsuleError) as e:
            cap.verify_cose_sign1(bytes.fromhex(neg["cose_sign1_hex"]), pub)
        assert "cose-signature" in str(e.value)

    def test_hash_envelope_with_content_type_rejected(self, V):
        pub = bytes.fromhex(V["test_key"]["public_hex"])
        neg = next(n for n in V["N_controls"] if n["id"] == "N5-hash-envelope-with-label-3")
        with pytest.raises(cap.CapsuleError) as e:
            cap.verify_cose_sign1(bytes.fromhex(neg["cose_sign1_hex"]), pub,
                                  hash_envelope=True)
        assert "rfc9995" in str(e.value)


class TestNegativeControls:
    def test_forbidden_member(self, V):
        neg = next(n for n in V["N_controls"] if n["id"] == "N1-forbidden-member")
        doc = json.loads(neg["capsule_jcs_utf8"])
        rules = [p["rule"] for p in cap.validate_capsule(doc)]
        assert "no-authority-member" in rules

    def test_source_url_rejected(self, V):
        neg = next(n for n in V["N_controls"] if n["id"] == "N2-source-not-a-digest")
        doc = json.loads(neg["capsule_jcs_utf8"])
        rules = [p["rule"] for p in cap.validate_capsule(doc)]
        assert "sources-digest-only" in rules

    def test_non_jcs_stored_line_rejected(self, V):
        neg = next(n for n in V["N_controls"] if n["id"] == "N3-stored-line-not-jcs")
        raw = neg["stored_line_utf8"].encode("utf-8")
        rules = [p["rule"] for p in cap.check_stored_bytes(raw, json.loads(raw))]
        assert "stored-bytes-are-jcs" in rules


class TestJcsRefusals:
    def test_float_refused_rather_than_guessed(self):
        with pytest.raises(cap.CapsuleError) as e:
            cap.jcs({"x": 1.5})
        assert "RFC 8785" in str(e.value)

    def test_nan_refused(self):
        with pytest.raises(cap.CapsuleError):
            cap.jcs({"x": float("nan")})

    def test_integers_fine(self):
        assert cap.jcs({"b": 1, "a": 2}) == b'{"a":2,"b":1}'


def test_conformance_runner_exits_zero():
    """The runner is the artefact we will send to the draft author, so it has to
    pass as a command, not only as an imported function."""
    r = subprocess.run([sys.executable,
                        os.path.join(ROOT, "scripts", "capsule_conformance.py")],
                       capture_output=True, text=True)
    assert r.returncode == 0, r.stdout + r.stderr
    assert "25/25 vectors pass" in r.stdout
